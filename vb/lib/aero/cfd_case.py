#!/usr/bin/env python
"""
Automated OpenFOAM (v1912, Ubuntu 24.04 'openfoam' apt package) external-aero case generator + runner +
post-processor for small UAV half-models.   STL(s) in  ->  force coefficients (JSON) out.

  python cfd_case.py run  --stl geom/wing/wing.stl --case cases/wing_a4 --alpha 4 --V 14 \
        --sref 0.31 --cref 0.195 --cofr 0.047 0 0 [--half] [--model kOmegaSST|kOmegaSSTLM] \
        [--surf-level 6 7] [--layers 5 --first-layer 3e-4] [--iters 1000] [--np 2] [--base 0.2]
  python cfd_case.py post --case cases/wing_a4

Pipeline (all logged to <case>/log.*, wall times in <case>/timing.json):
  blockMesh (domain from STL bbox) -> surfaceFeatureExtract -> decomposePar -> snappyHexMesh -parallel
  -> checkMesh -> simpleFoam -parallel (SIMPLEC, steady RANS) with forceCoeffs (total + per patch)
  -> post: mean of last N iterations, convergence (std/mean, residuals), JSON result.
Conventions: geometry in the structural frame (X aft, Y right, Z up, metres). Freestream is rotated by alpha
(flow from -X towards +X, positive alpha => flow from below). Half model on the y=0 symmetryPlane with
Aref = Sref/2. Cm about --cofr, nose-up positive (pitchAxis +Y in this frame).
"""
import argparse, glob, json, math, os, re, shutil, subprocess, sys, time
import numpy as np

HDR = """/*--------------------------------*- C++ -*----------------------------------*\\
  generated by cfd_case.py
\\*---------------------------------------------------------------------------*/
FoamFile {{ version 2.0; format ascii; class {cls}; {loc} object {obj}; }}
"""
SHIM = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tools", "foam_sha1_shim", "libfoam_sha1_shim.so")
# LD_PRELOAD shim works around the v1912/GCC-13 dictionary::digest() bug that kills all function objects
OF_ENV = ("source /usr/share/openfoam/etc/bashrc >/dev/null 2>&1 || true; "
          + (f"export LD_PRELOAD={SHIM}; " if os.path.exists(SHIM) else ""))


def hdr(obj, cls="dictionary", loc=""):
    return HDR.format(cls=cls, obj=obj, loc=(f'location "{loc}";' if loc else ""))


def stl_bbox(paths):
    lo = np.array([1e9] * 3); hi = -lo
    for p in paths:
        for line in open(p):
            s = line.split()
            if s and s[0] == "vertex":
                v = np.array([float(x) for x in s[1:4]])
                lo = np.minimum(lo, v); hi = np.maximum(hi, v)
    return lo, hi


def write(path, txt):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(txt)


def generate(a):
    c = os.path.abspath(a.case)
    if os.path.exists(c) and not a.keep:
        shutil.rmtree(c)
    os.makedirs(os.path.join(c, "constant", "triSurface"), exist_ok=True)
    names = []
    for s in a.stl:
        nm = os.path.splitext(os.path.basename(s))[0]
        shutil.copy(s, os.path.join(c, "constant", "triSurface", nm + ".stl"))
        names.append(nm)
    lo, hi = stl_bbox(a.stl)
    L = max(hi - lo)                         # largest body dimension
    cref = a.cref
    # ---- domain: ~10 L upstream / 20 L downstream would be ideal; use multiples of chord & span ---------
    x0 = lo[0] - a.up * L; x1 = hi[0] + a.down * L
    y0 = 0.0 if a.half else lo[1] - a.side * L; y1 = hi[1] + a.side * L
    z0 = lo[2] - a.side * L; z1 = hi[2] + a.side * L
    b = a.base
    nx, ny, nz = (max(1, int(round((x1 - x0) / b))), max(1, int(round((y1 - y0) / b))), max(1, int(round((z1 - z0) / b))))
    al = math.radians(a.alpha)
    U = (a.V * math.cos(al), 0.0, a.V * math.sin(al))
    lift = (-math.sin(al), 0.0, math.cos(al)); drag = (math.cos(al), 0.0, math.sin(al))
    Aref = a.sref / (2 if a.half else 1)
    nu = a.nu
    Tu = a.tu
    k_in = 1.5 * (Tu * a.V) ** 2
    om_in = k_in / (nu * a.visc_ratio)
    # Langtry-Menter inlet ReThetat correlation (Tu in %), Tu <= 1.3 %
    tup = Tu * 100
    rethetat = (1173.51 - 589.428 * tup + 0.2196 / tup ** 2) if tup <= 1.3 else 331.5 * (tup - 0.5658) ** -0.671
    meta = dict(case=c, stl=[os.path.abspath(s) for s in a.stl], patches=names, alpha=a.alpha, V=a.V, nu=nu,
                Re_cref=a.V * cref / nu, sref=a.sref, Aref=Aref, cref=cref, cofr=a.cofr, half=a.half,
                model=a.model, domain=[[x0, y0, z0], [x1, y1, z1]], base=b, blocks=[nx, ny, nz],
                surf_level=a.surf_level, layers=a.layers, first_layer=a.first_layer, iters=a.iters, np=a.np,
                k_in=k_in, omega_in=om_in, Tu=Tu, ReThetat_in=rethetat, U=U)
    json.dump(meta, open(os.path.join(c, "case.json"), "w"), indent=1)

    # ---------------------------------------------- system ---------------------------------------------
    write(f"{c}/system/blockMeshDict", hdr("blockMeshDict") + f"""
convertToMeters 1;
vertices ( ({x0} {y0} {z0}) ({x1} {y0} {z0}) ({x1} {y1} {z0}) ({x0} {y1} {z0})
           ({x0} {y0} {z1}) ({x1} {y0} {z1}) ({x1} {y1} {z1}) ({x0} {y1} {z1}) );
blocks ( hex (0 1 2 3 4 5 6 7) ({nx} {ny} {nz}) simpleGrading (1 1 1) );
boundary
(
    inlet  {{ type patch; faces ((0 4 7 3)); }}
    outlet {{ type patch; faces ((1 2 6 5)); }}
    far    {{ type patch; faces ((0 1 5 4) (3 7 6 2) (0 3 2 1) (4 5 6 7)); }}
);
""".replace("(0 1 5 4) (3 7 6 2)", "(3 7 6 2)" if a.half else "(0 1 5 4) (3 7 6 2)")
          .replace("boundary\n(", "boundary\n(\n    sym { type symmetryPlane; faces ((0 1 5 4)); }" if a.half else "boundary\n("))
    feats = "\n".join(f'        {{ file "{n}.eMesh"; level {a.surf_level[1]}; }}' for n in names)
    geo = "\n".join(f"    {n}.stl {{ type triSurfaceMesh; name {n}; }}" for n in names)
    refs = "\n".join(f"        {n} {{ level ({a.surf_level[0]} {a.surf_level[1]}); patchInfo {{ type wall; inGroups (body); }} }}" for n in names)
    lay = "\n".join(f'        "{n}" {{ nSurfaceLayers {a.layers}; }}' for n in names)
    # refinement boxes: near-body box (level 3) and wake box (level 2) and tight box (level 4)
    pad = 0.6 * cref
    box3 = ((lo[0] - pad, max(y0, lo[1] - pad), lo[2] - pad), (hi[0] + 3 * cref, hi[1] + pad, hi[2] + pad))
    box4 = ((lo[0] - 0.25 * cref, max(y0, lo[1] - 0.25 * cref), lo[2] - 0.25 * cref), (hi[0] + 0.6 * cref, hi[1] + 0.25 * cref, hi[2] + 0.25 * cref))
    box2 = ((lo[0] - 2 * cref, max(y0, lo[1] - 2 * cref), lo[2] - 2 * cref), (hi[0] + 12 * cref, hi[1] + 2 * cref, hi[2] + 2 * cref))
    # wake tilts with alpha: grow boxes in z on the downstream side
    def bx(name, b_):
        (p, q) = b_
        return f"    {name} {{ type searchableBox; min ({p[0]:.4f} {p[1]:.4f} {p[2]:.4f}); max ({q[0]:.4f} {q[1]:.4f} {q[2]:.4f}); }}"
    if a.layers > 0 and a.first_layer > 0:
        laytxt = f"""    relativeSizes false;
    firstLayerThickness {a.first_layer};
    expansionRatio {a.expansion};
    minThickness {a.first_layer * 0.3};"""
    else:
        laytxt = """    relativeSizes true;
    expansionRatio 1.2;
    finalLayerThickness 0.5;
    minThickness 0.1;"""
    loc = (x0 + 0.37 * (x1 - x0) * 0.1 + 1e-3, y1 - 0.123 * (y1 - y0), z1 - 0.137 * (z1 - z0))
    write(f"{c}/system/snappyHexMeshDict", hdr("snappyHexMeshDict") + f"""
castellatedMesh true;
snap            true;
addLayers       {"true" if a.layers > 0 else "false"};
geometry
{{
{geo}
{bx("box2", box2)}
{bx("box3", box3)}
{bx("box4", box4)}
}}
castellatedMeshControls
{{
    maxLocalCells 2000000;
    maxGlobalCells 6000000;
    minRefinementCells 10;
    maxLoadUnbalance 0.10;
    nCellsBetweenLevels 3;
    features
    (
{feats}
    );
    refinementSurfaces
    {{
{refs}
    }}
    resolveFeatureAngle 20;
    refinementRegions
    {{
        box2 {{ mode inside; levels ((1e15 2)); }}
        box3 {{ mode inside; levels ((1e15 3)); }}
        box4 {{ mode inside; levels ((1e15 4)); }}
    }}
    locationInMesh ({loc[0]:.5f} {loc[1]:.5f} {loc[2]:.5f});
    allowFreeStandingZoneFaces true;
}}
snapControls
{{
    nSmoothPatch 3;
    tolerance 2.0;
    nSolveIter 50;
    nRelaxIter 5;
    nFeatureSnapIter 10;
    implicitFeatureSnap false;
    explicitFeatureSnap true;
    multiRegionFeatureSnap false;
}}
addLayersControls
{{
    layers
    {{
{lay}
    }}
{laytxt}
    nGrow 0;
    featureAngle 130;
    slipFeatureAngle 30;
    nRelaxIter 3;
    nSmoothSurfaceNormals 1;
    nSmoothNormals 3;
    nSmoothThickness 10;
    maxFaceThicknessRatio 0.5;
    maxThicknessToMedialRatio 0.3;
    minMedialAxisAngle 90;
    nBufferCellsNoExtrude 0;
    nLayerIter 50;
    nRelaxedIter 20;
}}
meshQualityControls
{{
    maxNonOrtho 65;
    maxBoundarySkewness 20;
    maxInternalSkewness 4;
    maxConcave 80;
    minVol 1e-13;
    minTetQuality -1e30;
    minArea -1;
    minTwist 0.02;
    minDeterminant 0.001;
    minFaceWeight 0.05;
    minVolRatio 0.01;
    minTriangleTwist -1;
    nSmoothScale 4;
    errorReduction 0.75;
    relaxed {{ maxNonOrtho 75; }}
}}
mergeTolerance 1e-6;
""")
    write(f"{c}/system/surfaceFeatureExtractDict", hdr("surfaceFeatureExtractDict") + "\n".join(
        f"{n}.stl {{ extractionMethod extractFromSurface; includedAngle 150; subsetFeatures {{ nonManifoldEdges no; openEdges yes; }} writeObj no; }}"
        for n in names) + "\n")
    write(f"{c}/system/decomposeParDict", hdr("decomposeParDict") + f"numberOfSubdomains {a.np};\n// scotch is NOT available in the Ubuntu openfoam 1912 package (dummy stub)\nmethod hierarchical;\ncoeffs {{ n ({a.np} 1 1); delta 0.001; order xyz; }}\nhierarchicalCoeffs {{ n ({a.np} 1 1); delta 0.001; order xyz; }}\n")
    fo = f"""
    forceCoeffs_total
    {{
        type forceCoeffs; libs ("libforces.so"); writeControl timeStep; writeInterval 1; log false;
        patches ({" ".join(names)});
        rho rhoInf; rhoInf 1.0; CofR ({a.cofr[0]} {a.cofr[1]} {a.cofr[2]});
        liftDir ({lift[0]:.8f} 0 {lift[2]:.8f}); dragDir ({drag[0]:.8f} 0 {drag[2]:.8f}); pitchAxis (0 1 0);
        magUInf {a.V}; lRef {cref}; Aref {Aref};
    }}
""" + "".join(f"""
    forceCoeffs_{n}
    {{
        type forceCoeffs; libs ("libforces.so"); writeControl timeStep; writeInterval 1; log false;
        patches ({n});
        rho rhoInf; rhoInf 1.0; CofR ({a.cofr[0]} {a.cofr[1]} {a.cofr[2]});
        liftDir ({lift[0]:.8f} 0 {lift[2]:.8f}); dragDir ({drag[0]:.8f} 0 {drag[2]:.8f}); pitchAxis (0 1 0);
        magUInf {a.V}; lRef {cref}; Aref {Aref};
    }}
""" for n in names) + """
    yPlus1 { type yPlus; libs ("libfieldFunctionObjects.so"); writeControl writeTime; }
"""
    write(f"{c}/system/controlDict", hdr("controlDict") + f"""
application simpleFoam;
startFrom latestTime; startTime 0; stopAt endTime; endTime {a.iters}; deltaT 1;
writeControl timeStep; writeInterval {a.iters}; purgeWrite 1; writeFormat binary; writePrecision 8;
writeCompression off; timeFormat general; timePrecision 6; runTimeModifiable true;
functions
{{
{fo}
}}
""")
    lm = a.model == "kOmegaSSTLM"
    write(f"{c}/system/fvSchemes", hdr("fvSchemes") + f"""
ddtSchemes {{ default steadyState; }}
gradSchemes {{ default Gauss linear; grad(U) cellLimited Gauss linear 1; grad(k) cellLimited Gauss linear 1; grad(omega) cellLimited Gauss linear 1; }}
divSchemes
{{
    default none;
    div(phi,U) bounded Gauss linearUpwind grad(U);
    div(phi,k) bounded Gauss {"linearUpwind grad(k)" if a.second_order_turb else "upwind"};
    div(phi,omega) bounded Gauss {"linearUpwind grad(omega)" if a.second_order_turb else "upwind"};
    div(phi,ReThetat) bounded Gauss upwind;
    div(phi,gammaInt) bounded Gauss upwind;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}}
laplacianSchemes {{ default Gauss linear limited corrected 0.33; }}
interpolationSchemes {{ default linear; }}
snGradSchemes {{ default limited corrected 0.33; }}
wallDist {{ method meshWave; }}
""")
    write(f"{c}/system/fvSolution", hdr("fvSolution") + f"""
solvers
{{
    p {{ solver GAMG; smoother GaussSeidel; tolerance 1e-7; relTol 0.05; nCellsInCoarsestLevel 50; }}
    Phi {{ $p; }}
    "(U|k|omega|ReThetat|gammaInt)" {{ solver smoothSolver; smoother symGaussSeidel; tolerance 1e-8; relTol 0.1; nSweeps 1; }}
}}
SIMPLE
{{
    nNonOrthogonalCorrectors 0;
    consistent yes;
    residualControl {{ p 1e-5; U 1e-6; "(k|omega)" 1e-6; }}
}}
potentialFlow {{ nNonOrthogonalCorrectors 3; }}
relaxationFactors
{{
    fields {{ p 1.0; }}
    equations {{ U 0.7; "(k|omega)" 0.6; "(ReThetat|gammaInt)" 0.5; }}
}}
""")
    # ---------------------------------------------- constant --------------------------------------------
    write(f"{c}/constant/transportProperties", hdr("transportProperties") + f"transportModel Newtonian;\nnu {nu};\n")
    write(f"{c}/constant/turbulenceProperties", hdr("turbulenceProperties") + f"""
simulationType RAS;
RAS {{ RASModel {a.model}; turbulence on; printCoeffs on; }}
""")
    # ---------------------------------------------- 0 ---------------------------------------------------
    symm = "    sym { type symmetryPlane; }\n" if a.half else ""
    wallU = "    body { type noSlip; }\n"
    def field(name, cls, dim, internal, inlet, outlet, far, wall):
        return hdr(name, cls, "0") + f"""
dimensions {dim};
internalField uniform {internal};
boundaryField
{{
    #includeEtc "caseDicts/setConstraintTypes"
    inlet {{ {inlet} }}
    outlet {{ {outlet} }}
    far {{ {far} }}
{symm}    body {{ {wall} }}
}}
"""
    Us = f"({U[0]:.8f} {U[1]:.8f} {U[2]:.8f})"
    write(f"{c}/0.orig/U", field("U", "volVectorField", "[0 1 -1 0 0 0 0]", Us,
                                 f"type fixedValue; value uniform {Us};",
                                 f"type inletOutlet; inletValue uniform {Us}; value uniform {Us};",
                                 f"type freestreamVelocity; freestreamValue uniform {Us}; value uniform {Us};",
                                 "type noSlip;"))
    write(f"{c}/0.orig/p", field("p", "volScalarField", "[0 2 -2 0 0 0 0]", "0", "type zeroGradient;",
                                 "type fixedValue; value uniform 0;",
                                 "type freestreamPressure; freestreamValue uniform 0; value uniform 0;", "type zeroGradient;"))
    io = lambda v: f"type inletOutlet; inletValue uniform {v}; value uniform {v};"
    if a.first_layer > 0 and a.layers > 0 and a.first_layer < 1e-4:
        kw, ow, nw = "type fixedValue; value uniform 1e-14;", "type omegaWallFunction; value uniform 1e3;", "type nutLowReWallFunction; value uniform 0;"
    else:
        kw, ow, nw = "type kqRWallFunction; value uniform 1e-10;", "type omegaWallFunction; value uniform 1e3;", "type nutUSpaldingWallFunction; value uniform 0;"
    write(f"{c}/0.orig/k", field("k", "volScalarField", "[0 2 -2 0 0 0 0]", f"{k_in:.6e}", f"type fixedValue; value uniform {k_in:.6e};", io(f"{k_in:.6e}"), io(f"{k_in:.6e}"), kw))
    write(f"{c}/0.orig/omega", field("omega", "volScalarField", "[0 0 -1 0 0 0 0]", f"{om_in:.6e}", f"type fixedValue; value uniform {om_in:.6e};", io(f"{om_in:.6e}"), io(f"{om_in:.6e}"), ow))
    write(f"{c}/0.orig/nut", field("nut", "volScalarField", "[0 2 -1 0 0 0 0]", "0", "type calculated; value uniform 0;", "type calculated; value uniform 0;", "type calculated; value uniform 0;", nw))
    if lm:
        write(f"{c}/0.orig/ReThetat", field("ReThetat", "volScalarField", "[0 0 0 0 0 0 0]", f"{rethetat:.3f}", f"type fixedValue; value uniform {rethetat:.3f};", io(f"{rethetat:.3f}"), io(f"{rethetat:.3f}"), "type zeroGradient;"))
        write(f"{c}/0.orig/gammaInt", field("gammaInt", "volScalarField", "[0 0 0 0 0 0 0]", "1", "type fixedValue; value uniform 1;", io("1"), io("1"), "type zeroGradient;"))
    return meta


def sh(cmd, case, logname, timing):
    t0 = time.time()
    with open(os.path.join(case, f"log.{logname}"), "w") as f:
        p = subprocess.run(["bash", "-c", OF_ENV + cmd], cwd=case, stdout=f, stderr=subprocess.STDOUT)
    timing[logname] = round(time.time() - t0, 1)
    json.dump(timing, open(os.path.join(case, "timing.json"), "w"), indent=1)
    print(f"  {logname:24s} {timing[logname]:8.1f} s  rc={p.returncode}", flush=True)
    if p.returncode != 0:
        raise RuntimeError(f"{logname} failed, see {case}/log.{logname}")


def run(a):
    meta = generate(a)
    c = meta["case"]
    timing = {}
    par = f"mpirun --allow-run-as-root --oversubscribe -x LD_PRELOAD -np {a.np}" if a.np > 1 else ""
    pf = "-parallel" if a.np > 1 else ""
    print(f"case {c}: {meta['blocks']} background blocks, Re_c={meta['Re_cref']:.3g}, model {a.model}")
    sh("blockMesh", c, "blockMesh", timing)
    sh("surfaceFeatureExtract", c, "surfaceFeatureExtract", timing)
    if a.np > 1:
        sh("decomposePar -force", c, "decomposePar.mesh", timing)
    sh(f"{par} snappyHexMesh {pf} -overwrite", c, "snappyHexMesh", timing)
    if getattr(a, "mesh_only", False):
        sh(f"{par} checkMesh {pf} -constant", c, "checkMesh", timing)
        return post(a)
    if a.np > 1:
        # copy initial fields into each processor dir after meshing (fields must match the snapped mesh)
        sh("for d in processor*; do rm -rf $d/0; cp -r 0.orig $d/0; done", c, "copy0", timing)
        sh(f"{par} checkMesh {pf} -constant", c, "checkMesh", timing)
        sh(f"{par} simpleFoam {pf}", c, "simpleFoam", timing)
    else:
        sh("rm -rf 0; cp -r 0.orig 0", c, "copy0", timing)
        sh("checkMesh -constant", c, "checkMesh", timing)
        sh("simpleFoam", c, "simpleFoam", timing)
    return post(a)


def solve(a):
    """Re-use an existing (decomposed) mesh in --case: rewrite dictionaries for the new alpha/V/model,
    clear old results, run simpleFoam, post-process, keep result_a<alpha>_<model>.json."""
    a.keep = True
    meta = generate(a)
    c = meta["case"]
    timing = json.load(open(os.path.join(c, "timing.json"))) if os.path.exists(os.path.join(c, "timing.json")) else {}
    par = f"mpirun --allow-run-as-root --oversubscribe -x LD_PRELOAD -np {a.np}" if a.np > 1 else ""
    pf = "-parallel" if a.np > 1 else ""
    sh("rm -rf postProcessing processor*/[1-9]* processor*/0 && for d in processor*; do cp -r 0.orig $d/0; done", c, "copy0", timing)
    sh(f"{par} simpleFoam {pf}", c, "simpleFoam", timing)
    res = post(a)
    tag = f"a{a.alpha:g}_{a.model}"
    shutil.copy(os.path.join(c, "result.json"), os.path.join(c, f"result_{tag}.json"))
    shutil.copy(os.path.join(c, "log.simpleFoam"), os.path.join(c, f"log.simpleFoam_{tag}"))
    for fo in glob.glob(os.path.join(c, "postProcessing", "forceCoeffs_*")):
        dst = os.path.join(c, f"postProcessing_{tag}", os.path.basename(fo))
        shutil.rmtree(dst, ignore_errors=True); shutil.copytree(fo, dst)
    return res


def read_coeffs(case, name):
    fs = sorted(glob.glob(os.path.join(case, "postProcessing", name, "*", "*.dat")))
    fs = [f for f in fs if os.path.basename(f) in ("coefficient.dat", "forceCoeffs.dat")]
    if not fs:
        return None
    cols, rows = None, []
    for f in fs:
        for line in open(f):
            if line.startswith("#"):
                h = line[1:].split()
                if h and h[0] == "Time":
                    cols = h
                continue
            v = line.split()
            if v:
                rows.append([float(x) for x in v])
    arr = np.array(rows)
    return {k: arr[:, i] for i, k in enumerate(cols)} if cols else None


def post(a):
    c = os.path.abspath(a.case)
    meta = json.load(open(os.path.join(c, "case.json")))
    res = dict(case=c, alpha=meta["alpha"], V=meta["V"], model=meta["model"], Re_cref=meta["Re_cref"])
    n_avg = a.avg
    for fo in ["forceCoeffs_total"] + [f"forceCoeffs_{n}" for n in meta["patches"]]:
        d = read_coeffs(c, fo)
        if d is None:
            continue
        it = d["Time"]
        sel = it > it.max() - n_avg
        out = {}
        for k in ("Cd", "Cl", "CmPitch", "Cm", "Cs"):
            if k in d:
                v = d[k][sel]
                out[k] = float(v.mean()); out[k + "_std"] = float(v.std())
                out[k + "_osc_pct"] = float(100 * v.std() / max(abs(v.mean()), 1e-9))
        out["iterations"] = int(it.max())
        res[fo] = out
    # mesh stats
    try:
        txt = open(os.path.join(c, "log.checkMesh")).read()
        m = re.search(r"cells:\s+(\d+)", txt); res["cells"] = int(m.group(1)) if m else None
        res["mesh_ok"] = "Mesh OK" in txt
        m = re.search(r"Max non-orthogonality = ([\d.]+)", txt); res["max_nonortho"] = float(m.group(1)) if m else None
    except FileNotFoundError:
        pass
    try:
        txt = open(os.path.join(c, "log.snappyHexMesh")).read()
        ms = re.findall(r"^(\S+)\s+\d+\s+[\d.e+-]+\s+[\d.e+-]+\s+([\d.]+)\s*$", txt, re.M)
        res["layer_coverage_pct"] = {k: float(v) for k, v in ms}
    except FileNotFoundError:
        pass
    try:
        txt = open(os.path.join(c, "log.simpleFoam")).read()
        last = {}
        for m in re.finditer(r"Solving for (\w+), Initial residual = ([\d.e+-]+)", txt):
            last[m.group(1)] = float(m.group(2))
        res["final_initial_residuals"] = last
        m = re.findall(r"ExecutionTime = ([\d.]+) s", txt)
        res["solver_exec_s"] = float(m[-1]) if m else None
        res["converged_residualControl"] = "SIMPLE solution converged" in txt
        ys = re.findall(r"patch (\w+) y\+ : min = ([\d.e+-]+), max = ([\d.e+-]+), average = ([\d.e+-]+)", txt)
        if ys:
            res["yplus"] = {p: dict(min=float(mn), max=float(mx), avg=float(av)) for p, mn, mx, av in ys[-len(meta["patches"]):]}
    except FileNotFoundError:
        pass
    try:
        res["timing_s"] = json.load(open(os.path.join(c, "timing.json")))
    except FileNotFoundError:
        pass
    tot = res.get("forceCoeffs_total", {})
    res["CL"] = tot.get("Cl"); res["CD"] = tot.get("Cd"); res["Cm"] = tot.get("CmPitch", tot.get("Cm"))
    res["converged"] = bool(tot and tot.get("Cl_osc_pct", 100) < 0.5 and tot.get("Cd_osc_pct", 100) < 1.0)
    json.dump(res, open(os.path.join(c, "result.json"), "w"), indent=1)
    print(json.dumps({k: res.get(k) for k in ("CL", "CD", "Cm", "cells", "converged", "solver_exec_s")}, indent=0))
    return res


