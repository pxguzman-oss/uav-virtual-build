"""Adapter: plan + mass + aero dataset + propulsion -> aircraft_model JSON (schema/aircraft_model.schema.json)
for the sim generator (JSBSim XML, SIM_Plane fallback, servo-map .parm) and the SITL bridge.

Frames: positions and CG in the design/structural frame (x aft, y right, z up, m); inertia about the CG in
body FRD with Ixz = +int(x z dm) (JSBSim convention); thrust directions in body FRD."""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

from .. import plan as P

ROOT = Path(__file__).resolve().parents[2]
# ArduPilot channel map (Matek H743-WING-style): S1 aileron L, S2 ruddervator/elevator L, S3 pusher ESC,
# S4 ruddervator R, S5 aileron R, S6/S7 flaps, S9-S12 lift motors (quad-X order 1..4)
CHAN = {"aileron_left": 1, "ruddervator_left": 2, "ruddervator_right": 4, "aileron_right": 5, "flap_left": 6, "flap_right": 7,
        "elevator": 2, "rudder": 4}
SIGN = {"aileron_left": 1, "aileron_right": -1, "ruddervator_left": -1, "ruddervator_right": -1, "flap_left": 1, "flap_right": -1}
OCV_SOC = [0.0, 0.05, 0.10, 0.20, 0.30, 0.40, 0.50, 0.60, 0.70, 0.80, 0.90, 1.00]
OCV_V = [3.00, 3.30, 3.42, 3.53, 3.60, 3.66, 3.72, 3.80, 3.88, 3.97, 4.07, 4.18]   # generic NMC/NCA 21700


def to_frd(v):
    return [-v[0], v[1], -v[2]]


def prop_table(prop_cfg, plan_dir):
    ref = prop_cfg.get("data", "")
    f = ROOT / "data" / "props" / f"{ref[9:]}.json" if ref.startswith("embedded:") else Path(plan_dir) / ref
    t = json.loads(Path(f).read_text())
    tab = dict(source=t.get("source", str(f)), J=t["J"], CT=t["CT"], CP=t["CP"])
    if t.get("rpm"):
        tab["rpm"] = t["rpm"]
    return tab


def build(plan, mass, aero_ds, sim_block, prop_res, plan_dir, launch_cfg=None):
    w = P.main_wing(plan)
    mg = P.mac_geometry(w)
    af = plan["airframe"]
    st = af["fuselage"].get("stations") or [[af["fuselage"].get("x_nose", -0.3), 0.1, 0.1, 0.0], [0.6, 0.04, 0.04, 0.0]]
    x_nose, x_tail = st[0][0], st[-1][0]
    I = mass["inertia_frd"]
    name = P.slug(plan["meta"]["name"]) + "_" + plan["meta"].get("variant", "base")
    m = {"schema_version": "1.0", "name": name,
         "provenance": {"status": "GENERATED by vbuild flightmodel stage from the build plan",
                        "geometry": f"plan '{plan['meta']['name']}' rev {plan['meta'].get('revision')} ({plan['meta'].get('variant')})",
                        "mass": f"mass stage ({mass['model']} model): {mass['mass_kg']:.3f} kg",
                        "aero": "aero_lowfi stage: AeroBuildup tables + AVL derivatives",
                        "prop": "data/props APC PER3 (computed by APC); ct/cp_scale from plan",
                        "battery": f"{plan['energy']['cell']['model']} {plan['energy']['series']}S{plan['energy']['parallel']}P"},
         "geometry": {"wing_area_m2": mg["area"], "span_m": w["span"], "mac_m": mg["mac"], "mac_le_x_m": mg["x_le_mac"],
                      "length_m": x_tail - x_nose},
         "mass": {"mass_kg": mass["mass_kg"], "cg_m": list(mass["cg_m"]),
                  "inertia_kgm2": {"Ixx": I["Ixx"], "Iyy": I["Iyy"], "Izz": I["Izz"], "Ixz": I["Ixz"]}},
         "aero": dict(sim_block["aero"], stall_asymmetry=float(P.val(((plan.get("analysis") or {}).get("sitl") or {}).get("stall_asymmetry"), 0.075))),
         "surfaces": [], "propulsion": {"motors": []}}
    # surfaces
    cs_by_fn = {}
    for ls in af["lifting_surfaces"]:
        for cs in ls.get("control_surfaces", []):
            cs_by_fn[cs["function"]] = cs
    for s in aero_ds["surfaces"]:
        nm, kind = s["name"], s["kind"]
        cs = cs_by_fn.get(kind, {})
        m["surfaces"].append(dict(name=nm, kind=kind, pwm=dict(channel=CHAN[nm], sign=SIGN.get(nm, 1)),
                                  max_deflection_deg=cs.get("max_defl_deg", s.get("max_deflection_deg", 20)),
                                  rate_limit_deg_s=cs.get("servo_rate_deg_s", 300), lag_s=0.02,
                                  derivatives_per_rad=s["derivatives_per_rad"]))
    # motors
    used = {c["pwm"]["channel"] for c in m["surfaces"]}
    for u in plan["propulsion"]["units"]:
        mo, pr, esc = u["motor"], u["prop"], u["esc"]
        motor = dict(kv_rpm_per_v=P.val(mo["kv"]), rm_ohm=P.val(mo["rm"]) + esc.get("r_on", 0.004), i0_a=P.val(mo["i0"]),
                     i0_ref_v=mo.get("i0_ref_V", 10), i_max_a=mo.get("i_max", 40), rotor_inertia_kgm2=mo.get("rotor_inertia", 1e-5),
                     mass_kg=mo.get("mass", 0.07))
        prop = dict(label=pr.get("model", ""), diameter_m=pr["diameter"], pitch_m=pr.get("pitch", 0.1),
                    inertia_kgm2=pr.get("inertia", 2e-5 * (pr["diameter"] / 0.254) ** 4), thrust_scale=pr.get("ct_scale", 1.0),
                    power_scale=pr.get("cp_scale", 1.0), table=prop_table(pr, plan_dir))
        tdir = to_frd(u.get("thrust_axis", [-1, 0, 0]))
        if u["role"] in ("cruise", "tilt"):
            for i, pos in enumerate(u.get("positions", [[x_tail, 0, 0]])):
                ch = 3 if i == 0 else max(used | {8}) + 1
                used.add(ch)
                m["propulsion"]["motors"].append(dict(name=u["name"] + (str(i + 1) if u["count"] > 1 else ""), role="forward",
                                                      pwm=dict(channel=ch), position_m=list(pos), thrust_dir_body=tdir, spin=1,
                                                      motor=motor, esc=dict(pwm_min=1000, pwm_max=2000, spin_min=0.0, regen=False,
                                                                            efficiency=0.97), prop=prop))
        else:   # lift: quad-X order 1..4 -> SERVO9..12, spins CCW, CCW, CW, CW
            spins = u.get("spin") or [1, 1, -1, -1, 1, -1, 1, -1][:u["count"]]
            for i, pos in enumerate(u["positions"]):
                ch = 9 + i
                used.add(ch)
                m["propulsion"]["motors"].append(dict(name=f"lift{i + 1}", role="lift", pwm=dict(channel=ch), position_m=list(pos),
                                                      thrust_dir_body=tdir, spin=spins[i], motor=motor,
                                                      esc=dict(pwm_min=1000, pwm_max=2000, spin_min=0.0, regen=False, efficiency=0.96),
                                                      prop=prop))
    e = plan["energy"]
    c = e["cell"]
    m["battery"] = dict(chemistry=c.get("chemistry", "li_ion_nmc"), cell=c["model"], cells_series=e["series"],
                        cells_parallel=e["parallel"], cell_capacity_ah=c["capacity_Ah"], cell_r_dc_ohm=P.val(c["r_dc"]),
                        cell_rc_r_ohm=c.get("r_rc", 0.5 * P.val(c["r_dc"])), cell_rc_tau_s=c.get("rc_tau_s", 30),
                        pack_extra_r_ohm=e.get("pack_wiring_r", 0.006),
                        ocv_table=dict(soc=c.get("ocv_soc", OCV_SOC), v_cell=c.get("ocv_v", OCV_V)),
                        v_cell_cutoff=max(c.get("v_min", 2.8), 2.8), initial_soc=1.0, mass_kg=c["mass"] * e["series"] * e["parallel"])
    m["electrical"] = {"avionics_power_w": plan.get("avionics", {}).get("avionics_power_W", 4.0)}
    # ground contacts
    z_bot = min(s[3] - s[2] / 2 for s in st)
    zb_tail = st[-1][3] - st[-1][2] / 2
    z_wing = w.get("z_le_root", 0.0)
    ct = w["tip_chord"]
    x_tip = math.tan(math.radians(w.get("sweep_c4_deg", 0.0) or 0.0)) * w["span"] / 2 + 0.25 * (w["root_chord"] - ct)
    contacts = [dict(name="nose", position_m=[x_nose + 0.03, 0.0, st[1][3] - st[1][2] / 2]),
                dict(name="belly", position_m=[mass["cg_m"][0] + 0.03, 0.0, z_bot]),
                dict(name="tail", position_m=[x_tail, 0.0, zb_tail]),
                dict(name="lwingtip", position_m=[x_tip + ct / 2, -w["span"] / 2, z_wing]),
                dict(name="rwingtip", position_m=[x_tip + ct / 2, w["span"] / 2, z_wing])]
    is_vtol = bool(P.units(plan, "lift"))
    if is_vtol:
        for b in af.get("booms", []):
            for end, tag in ((b["root"], "r"), (b["tip"], "f")):
                for sgn, side in ((1, "r"), (-1, "l")):
                    contacts.append(dict(name=f"skid_{tag}{side}", position_m=[end[0], sgn * abs(end[1]), z_bot - 0.01]))
        for cc in contacts:
            cc.update(spring_n_per_m=4000, damping_n_s_per_m=120, static_friction=0.8, dynamic_friction=0.6)
    m["ground"] = {"contacts": contacts}
    lc = launch_cfg or {}
    if af.get("launch", {}).get("method", "hand") == "vtol":
        m["launch"] = {"type": "vtol"}
    else:
        m["launch"] = dict(type=af.get("launch", {}).get("method", "hand"), hold_height_m=lc.get("hold_height", 1.6), hold_pitch_deg=8,
                           accel_mps2=lc.get("launch_accel", 25), duration_s=lc.get("launch_duration", 0.45), release_pitch_deg=10)
    return m
